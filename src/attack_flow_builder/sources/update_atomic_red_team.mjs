import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

/**
 * Atomic Red Team Git revision used for both coverage discovery and runtime
 * URLs. Keep this as "master" to follow upstream, or replace it with a commit
 * SHA to deliberately pin Atomic Red Team content to an immutable revision.
 */
const ATOMIC_RED_TEAM_REVISION = "master";
const ATOMIC_RED_TEAM_TREE_URL =
    `https://api.github.com/repos/redcanaryco/atomic-red-team/git/trees/${ATOMIC_RED_TEAM_REVISION}?recursive=1`;
const ATOMIC_DIRECTORY_PATTERN = /^atomics\/(T\d{4}(?:\.\d{3})?)\/\1\.yaml$/;
const OUTPUT_FILE = "../src/assets/configuration/AttackFlowTemplates/AtomicRedTeam.ts";
const REPOSITORY_URL = "https://github.com/redcanaryco/atomic-red-team";

/**
 * Gets Atomic Red Team technique coverage from its Git tree.
 *
 * The tree is a single source of truth for coverage and avoids relying on the
 * large aggregate index file or issuing a request per technique.
 *
 * @returns {Promise<string[]>}
 */
async function fetchAtomicRedTeamCoverage() {
    const response = await fetch(ATOMIC_RED_TEAM_TREE_URL, {
        headers: { Accept: "application/vnd.github+json" }
    });
    if (!response.ok) {
        throw new Error(`Unable to fetch Atomic Red Team coverage (${response.status} ${response.statusText}).`);
    }

    const tree = await response.json();
    if (tree.truncated) {
        throw new Error("Atomic Red Team Git tree response was truncated.");
    }
    if (!Array.isArray(tree.tree)) {
        throw new Error("Atomic Red Team Git tree response has an unexpected shape.");
    }

    return tree.tree
        .filter(entry => entry.type === "blob" && typeof entry.path === "string")
        .map(entry => entry.path.match(ATOMIC_DIRECTORY_PATTERN)?.[1])
        .filter(Boolean)
        .sort((left, right) => left.localeCompare(right));
}

/**
 * Writes the static coverage manifest consumed by the Builder UI.
 * @param {string[]} techniqueIds
 */
function writeAtomicRedTeamManifest(techniqueIds) {
    const output = [
        "/**",
        " * Generated by sources/update_atomic_red_team.mjs. Do not edit manually.",
        ` * Atomic Red Team revision: ${ATOMIC_RED_TEAM_REVISION}`,
        " */",
        `export const atomicRedTeamRevision = ${JSON.stringify(ATOMIC_RED_TEAM_REVISION)};`,
        `export const atomicRedTeamBaseUrl = ${JSON.stringify(`${REPOSITORY_URL}/blob/${ATOMIC_RED_TEAM_REVISION}/atomics`)};`,
        `export const atomicRedTeamRawBaseUrl = ${JSON.stringify(`https://raw.githubusercontent.com/redcanaryco/atomic-red-team/${ATOMIC_RED_TEAM_REVISION}/atomics`)};`,
        "",
        "export const atomicRedTeamTechniqueIds: ReadonlySet<string> = new Set(",
        "    [",
        techniqueIds.map((techniqueId, index) =>
            `        ${JSON.stringify(techniqueId)}${index < techniqueIds.length - 1 ? "," : ""}`
        ).join("\n"),
        "    ]",
        ");",
        ""
    ].join("\n");
    const path = resolve(dirname(fileURLToPath(import.meta.url)), OUTPUT_FILE);
    writeFileSync(path, output);
    console.log(`→ Generated Atomic Red Team coverage for ${techniqueIds.length} techniques at ${ATOMIC_RED_TEAM_REVISION}.`);
}

/** Refreshes the Atomic Red Team coverage manifest. */
export default async function updateAtomicRedTeam() {
    console.log("→ Downloading Atomic Red Team coverage...");
    const techniqueIds = await fetchAtomicRedTeamCoverage();
    writeAtomicRedTeamManifest(techniqueIds);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
    await updateAtomicRedTeam();
}
